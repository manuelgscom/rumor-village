/**
 * Fills "{key}" placeholders.
 * @param {string} s
 * @param {Object<string, string|number>} vars
 */
export function fill(s, vars) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
